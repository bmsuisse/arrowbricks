pub fn build_fetch_results(op: &OperationHandle, max_rows: i64, max_bytes: i64) -> Vec<u8> {
    build_call("FetchResults", |w| {
        w.write_field_begin(ttype::STRUCT, 1);
        op.write(w);
        w.write_field_begin(ttype::I32, 2); // orientation = FETCH_NEXT
        w.write_i32(0);
        w.write_field_begin(ttype::I64, 3);
        w.write_i64(max_rows);
        w.write_field_begin(ttype::I16, 4); // fetchType = 0 (query results, not logs)
        w.write_i16(0);
        w.write_field_begin(ttype::I64, 1281);
        w.write_i64(max_bytes);
        w.write_field_begin(ttype::BOOL, 1283); // includeResultSetMetadata
        w.write_bool(true);
        w.write_field_stop();
    })
}
