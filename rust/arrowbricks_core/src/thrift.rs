// ---- The 7 RPC message pairs this crate needs ----------------------------

/// Builds one full Thrift RPC call message: `writeMessageBegin(method, CALL,
/// seqid)` + an "args" struct with the request at field 1 (matching every
/// generated `<Method>_args` struct in `TCLIService.py` -- always exactly
/// one field, `req`, at id 1) + field-stop. `seqid` is always 0 -- this
/// crate makes one synchronous call at a time per HTTP request/response
/// pair (no multiplexing over one transport the way a persistent Thrift
/// socket connection might), so distinguishing concurrent in-flight calls
/// by sequence id is never needed; matches `databricks-sql-connector`'s own
/// `self._seqid` which is likewise never incremented in the Databricks
/// Thrift-over-HTTP client.
fn build_call(method: &str, write_req: impl FnOnce(&mut Writer)) -> Vec<u8> {
    let mut w = Writer::new();
    w.write_message_begin(method, MESSAGE_TYPE_CALL, 0);
    w.write_field_begin(ttype::STRUCT, 1);
    write_req(&mut w);
    w.write_field_stop();
    w.into_bytes()
}

/// Parses one full Thrift RPC reply message: `readMessageBegin` (raising on
/// `EXCEPTION`), then the "result" struct, which always carries the actual
/// response at field id 0 (`success`, matching every generated
/// `<Method>_result` struct).
fn parse_reply<T>(bytes: &[u8], read_success: impl FnOnce(&mut Reader) -> TResult<T>) -> TResult<T> {
    let mut r = Reader::new(bytes);
    let (_name, msg_type, _seqid) = r.read_message_begin()?;
    if msg_type == MESSAGE_TYPE_EXCEPTION {
        return Err(ThriftError(read_application_exception(&mut r)?));
    }
    let mut read_success = Some(read_success);
    let mut result = None;
    loop {
        let (ft, id) = r.read_field_begin()?;
        if ft == ttype::STOP {
            break;
        }
        if id == 0 && ft == ttype::STRUCT {
            // `take()` is just satisfying the borrow checker for an `FnOnce`
            // inside a loop that only ever calls it once in practice.
            let f = read_success
                .take()
                .ok_or_else(|| ThriftError("duplicate `success` field in thrift reply".to_string()))?;
            result = Some(f(&mut r)?);
        } else {
            r.skip(ft)?;
        }
    }
    result.ok_or_else(|| ThriftError("thrift reply had no `success` field".to_string()))
}

pub fn build_open_session(req: &OpenSessionReq) -> Vec<u8> {
    build_call("OpenSession", |w| req.write(w))
}
pub fn parse_open_session(bytes: &[u8]) -> TResult<OpenSessionResp> {
    parse_reply(bytes, OpenSessionResp::read)
}

