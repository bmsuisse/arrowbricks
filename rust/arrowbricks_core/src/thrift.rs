pub struct OperationStatusResp {
    pub status: Status,
    pub operation_state: Option<i32>,
    pub error_message: Option<String>,
    pub display_message: Option<String>,
}

impl OperationStatusResp {
    fn read(r: &mut Reader) -> TResult<Self> {
        let mut status = None;
        let mut operation_state = None;
        let mut error_message = None;
        let mut display_message = None;
        loop {
            let (ft, id) = r.read_field_begin()?;
            if ft == ttype::STOP {
                break;
            }
            match (id, ft) {
                (1, ttype::STRUCT) => status = Some(Status::read(r)?),
                (2, ttype::I32) => operation_state = Some(r.read_i32()?),
                (5, ttype::STRING) => error_message = Some(r.read_string()?),
                // Field 1281, not 12 -- found while building the Thrift
                // mock test infra (this session) by cross-checking against
                // `databricks-sql-connector`'s own real, installed,
                // Apache-Thrift-compiler-generated `ttypes.py`: its
                // `TGetOperationStatusResp.thrift_spec` has no field 12 at
                // all; `displayMessage` is field 1281. Before this fix, a
                // real server's `GetOperationStatus.displayMessage` was
                // silently skipped by the `(_, ft) => r.skip(ft)?` catch-all
                // below (an unrecognized field id, not an error) --
                // `terminal_error()` still worked correctly in practice
                // because it checks the *top-level* `Status.display_message`
                // (field 6 of `TStatus`, correctly mapped, see `Status::read`
                // above) before ever falling back to this
                // operation-state-specific one, so this was a real but
                // narrow, never-observed-in-practice bug, not a regression
                // in any existing test or real-workspace verification.
                (1281, ttype::STRING) => display_message = Some(r.read_string()?),
                (_, ft) => r.skip(ft)?,
            }
        }
        Ok(Self {
            status: status.ok_or_else(|| ThriftError("TGetOperationStatusResp missing status".into()))?,
            operation_state,
            error_message,
            display_message,
        })
    }

    /// Terminal-with-error states (`ERROR`/`CANCELED`/`CLOSED`/`TIMEDOUT`)
    /// surface a message; `None` means either still running/pending, or
    /// cleanly `FINISHED`.
    pub fn terminal_error(&self) -> Option<String> {
        if let Some(e) = self.status.error() {
            return Some(e);
        }
        match self.operation_state {
            Some(operation_state::ERROR) => Some(
                self.display_message
                    .clone()
                    .or_else(|| self.error_message.clone())
                    .unwrap_or_else(|| "Thrift statement failed".to_string()),
            ),
            Some(operation_state::CANCELED) => Some("Thrift statement was canceled".to_string()),
            Some(operation_state::CLOSED) => Some("Thrift statement was closed server-side".to_string()),
            Some(operation_state::TIMEDOUT) => Some("Thrift statement timed out server-side".to_string()),
            _ => None,
        }
    }

    pub fn is_finished(&self) -> bool {
        self.operation_state == Some(operation_state::FINISHED)
    }
}

