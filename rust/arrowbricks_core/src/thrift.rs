        // Claims 100 elements but the element-type byte and all data are
        // missing -- read_list_begin hits end-of-buffer trying to read past
        // what's given.
        let mut r = Reader::new(&[ttype::LIST as u8, 0, 0, 0, 100]);
        let err = r.skip(ttype::LIST);
